def _ass_color_to_inline(ass_color: str) -> str:
    hexpart = ass_color.strip().removeprefix("&H").removesuffix("&")
    return f"&H{hexpart[-6:]}&"


def _overlay_event(o, width: int, height: int, style: CaptionStyle) -> str:
    """One Dialogue line for a text overlay, drawn on layer 1 (above captions),
    placed and line-broken inside the platform-safe rectangle."""
    an = {"top": 8, "center": 5, "bottom": 2}[o.position]
    r = safe_rect(width, height)
    size = max(12, o.font_size_px)
    if o.position == "top":
        margin_v = int(round(r.y0))
    elif o.position == "bottom":
        # Sit above the caption band (its bottom is the safe bottom edge,
        # two lines tall at most) so the two never collide.
        margin_v = int(round(height - r.y1 + style.font_size_px * 2.6))
    else:
        margin_v = 0
    fad = f"\\fad({max(0, o.fade_ms)},{max(0, o.fade_ms)})" if o.fade_ms > 0 else ""
    tags = (
        f"{{\\an{an}{fad}\\fs{size}"
        f"\\c{_ass_color_to_inline(o.color)}\\3c{_ass_color_to_inline(o.outline_color)}"
        f"\\b{1 if o.bold else 0}}}"
    )
    lines: list[str] = []
    for paragraph in strip_emoji(o.text.replace("\r", "")).split("\n"):
        lines.extend(
            wrap_to_width(
                paragraph.split(), style.font_family, size, r.width - 2 * (5 + 2) - 4
            )
            or [""]
        )
    text = "\\N".join(_escape_text(line) for line in lines)
    start = max(0.0, o.start_sec)
    end = max(start + 0.1, o.end_sec)
    return (
        f"Dialogue: 1,{_fmt_time(start)},{_fmt_time(end)},Overlay,,0,0,{margin_v},,"
        f"{tags}{text}\n"
    )


def _word_text(w: TranscriptWord) -> str:
    return strip_emoji(w.word.strip())


def _pack_by_width(
    words: list[TranscriptWord],
    style: CaptionStyle,
    max_width: float,
    max_lines: int,
    max_chars: int,
    gap_break: float = 0.7,
) -> list[list[TranscriptWord]]:
    """Group words into events that fit `max_lines` lines of `max_width`
    (measured in the real font) and `max_chars` per line; a pause longer
    than `gap_break` always starts a new event."""
    bold = _measure_bold(style.font_family)
    events: list[list[TranscriptWord]] = []
    current: list[TranscriptWord] = []
    for i, w in enumerate(words):
        trial = [*current, w]
        lines = wrap_to_width(
            [_word_text(x) for x in trial], style.font_family, style.font_size_px, max_width, bold=bold
        )
        too_long = len(lines) > max_lines or any(len(ln) > max_chars for ln in lines if " " in ln)
        if current and too_long:
            events.append(current)
            current = [w]
        else:
            current = trial
        if i + 1 < len(words) and words[i + 1].start - w.end > gap_break:
            events.append(current)
            current = []
    if current:
        events.append(current)
    return [e for e in events if e]


def _punch_chunks(
    words: list[TranscriptWord], style: CaptionStyle, max_width: float
) -> list[list[TranscriptWord]]:
    """1-3 word chunks: break at the word limit, after punctuation, at a
    pause, or when the next word would not fit on one safe-width line."""
    bold = _measure_bold(style.font_family)
    chunks: list[list[TranscriptWord]] = []
    current: list[TranscriptWord] = []
    for i, w in enumerate(words):
        if current:
            trial = " ".join(_word_text(x) for x in [*current, w])
            if text_width(trial, style.font_family, style.font_size_px, bold) > max_width:
                chunks.append(current)
                current = []
        current.append(w)
        ends_clause = w.word.rstrip().endswith((".", ",", "!", "?", ";", ":"))
        paused = i + 1 < len(words) and words[i + 1].start - w.end > 0.35
        if len(current) >= style.punch_max_words or ends_clause or paused:
            chunks.append(current)
            current = []
    if current:
        chunks.append(current)
    return chunks


def _render_punch(
    words: list[TranscriptWord], mt, config: ComposeConfig, preferred: list[bool] | None = None
) -> list[str]:
    style = config.captions
    width, height = config.resolution
    max_w = _safe_width(width, height, outline=style.outline_width_px, shadow=style.shadow_px)
    bold = _measure_bold(style.font_family)
    if preferred is not None:
        keep = [bool(_word_text(w)) for w in words]
        preferred = [p for p, k in zip(preferred, keep) if k]
    words = [w for w in words if _word_text(w)]
    chunks = _punch_chunks(words, style, max_w)
    grid = None
    if preferred is not None:
        # The AI's key words, reshaped to the chunk layout.
        it = iter(preferred)
        grid = [[next(it, False) for _ in c] for c in chunks]
    lit = pick_keywords([[_word_text(w) for w in c] for c in chunks], preferred=grid)
    on = _inline_color(style.highlight_color)
    off = _inline_color(style.primary_color)
    out: list[str] = []
    for ci, chunk in enumerate(chunks):
        start = mt(chunk[0].start)
        end = mt(chunk[-1].end) + 0.2
        if ci + 1 < len(chunks):
            nxt = mt(chunks[ci + 1][0].start)
            # Back-to-back while the speaker keeps going, so nothing flickers.
            end = nxt if nxt - mt(chunk[-1].end) < 0.35 else min(end, nxt)
        if end <= start + 0.1:
            end = start + 0.25
        tokens = []
        for wi, w in enumerate(chunk):
            tok = _escape_text(_word_text(w))
            tokens.append(f"{{{on}}}{tok}{{{off}}}" if (ci, wi) in lit else tok)
        plain = " ".join(_word_text(w) for w in chunk)
        size = fit_size(plain, style.font_family, style.font_size_px, max_w, bold=bold)
        size_tag = f"\\fs{size:.0f}" if size < style.font_size_px else ""
        # An 80ms pop from 108% — enough to register the change, not a bounce.
        pop = f"{{{size_tag}\\fscx108\\fscy108\\t(0,80,\\fscx100\\fscy100)}}"
        out.append(_event_raw(start, end, pop + " ".join(tokens)))
    return out


def _render_word_events(
    words: list[TranscriptWord], mt, config: ComposeConfig, preferred: list[bool] | None = None
) -> list[str]:
    """Caption events for one run of words, in the configured mode. `mt` maps
    a word-local time to the mezzanine timeline; `preferred` flags the AI's
    key words (punch mode only — karaoke lights every word, static none)."""
    style = config.captions
    width, height = config.resolution
    max_w = _safe_width(width, height, outline=style.outline_width_px, shadow=style.shadow_px)
    if style.mode == "punch":
        return _render_punch(words, mt, config, preferred)
    out: list[str] = []
    if style.mode == "karaoke":
        highlight = _inline_color(style.highlight_color)
        chunks = _pack_by_width(words, style, max_w, 1, style.karaoke_max_chars)
        for chunk in chunks:
            cw = [w for w in chunk if _word_text(w)]
            if not cw:
                continue
            tokens = [_escape_text(_word_text(w)) for w in cw]
            for k, w in enumerate(cw):
                start = mt(cw[0].start) if k == 0 else mt(w.start)
                end = mt(cw[k + 1].start) if k + 1 < len(cw) else mt(cw[-1].end)
                if end <= start:
                    end = start + 0.15
                line = " ".join(
                    f"{{{highlight}\\b1}}{tok}{{\\r}}" if j == k else tok
                    for j, tok in enumerate(tokens)
                )
                out.append(_event_raw(start, end, line))
    else:
        bold = _measure_bold(style.font_family)
        for ev in _pack_by_width(words, style, max_w, style.max_lines, style.max_chars_per_line):
            texts = [_word_text(w) for w in ev if _word_text(w)]
            if not texts:
                continue
            start = mt(ev[0].start)
            end = mt(ev[-1].end)
            if end <= start:
                end = start + 0.3
            lines = wrap_to_width(texts, style.font_family, style.font_size_px, max_w, bold=bold)
            out.append(_event_raw(start, end, "\\N".join(_escape_text(ln) for ln in lines)))
    return out


def effective_analyses(
    analysis: AnalysisReport, analyses: "dict[str, AnalysisReport | None] | None"
) -> "dict[str, AnalysisReport | None]":
    """Per-asset reports with any user transcript override swapped in.
    Legacy single-asset callers get {reel asset: analysis}."""
    effective: dict[str, AnalysisReport | None] = dict(analyses or {})
    effective.setdefault(analysis.asset_id, analysis)
    try:
        from reelforge_core.transcript_store import load_override_sync

        for aid, rep in list(effective.items()):
            if rep is None:
                continue
            override = load_override_sync(aid)
            if override is not None:
                effective[aid] = rep.model_copy(update={"transcript": override})
    except Exception:  # pragma: no cover
        pass
    return effective


def clip_shots(clips: list, default_asset_id: str) -> list[tuple[str | None, float | None, float | None, float]]:
    """(asset_id, src_start, src_end, duration) per rendered shot. Photos map
    to no source span; sped shots are muted (v1 rule) so their words are
    suppressed — both still advance mezzanine time."""
    shots: list[tuple[str | None, float | None, float | None, float]] = []
    for c in clips:
        if c.is_photo or getattr(c, "speed", 1.0) != 1.0:
            shots.append((None, None, None, c.duration))
        else:
            shots.append((c.asset_id or default_asset_id, c.in_ts, c.out_ts, c.duration))
    return shots


def map_segments(
    shots: list[tuple[str | None, float | None, float | None, float]],
    xfades: list[float],
) -> list[tuple[str, float, float, float]]:
    """(asset, src_start, src_end, mezz_start) for every shot that carries
    source audio, with each crossfade's overlap reclaimed."""
    n_cuts = max(0, len(shots) - 1)
    xf = list(xfades)[:n_cuts] + [0.0] * max(0, n_cuts - len(xfades))
    segments: list[tuple[str, float, float, float]] = []
    cum = 0.0
    reclaimed = 0.0
    for position, (aid, src_start, src_end, dur) in enumerate(shots):
        if position > 0:
            reclaimed += xf[position - 1]
        if aid is not None and src_start is not None and src_end is not None:
            segments.append((aid, src_start, src_end, cum - reclaimed))
        cum += dur
    return segments


def segment_words(rep: AnalysisReport, src_start: float, src_end: float) -> list[TranscriptWord]:
    """The transcript's words whose midpoint falls inside [src_start, src_end]."""
    out: list[TranscriptWord] = []
    if rep.transcript is None:
        return out
    for seg in rep.transcript.segments:
        if seg.end < src_start or seg.start > src_end:
            continue
        for w in seg.words:
            mid = (w.start + w.end) / 2.0
            if src_start <= mid <= src_end + 1e-6:
                out.append(w)
    return out


def build_captions(
    reel: RankedReel,
    analysis: AnalysisReport,
    config: ComposeConfig,
    reel_dir: Path,
    end_trims: list[float] | None = None,
    clips: list | None = None,
    analyses: "dict[str, AnalysisReport | None] | None" = None,
    overlays: list | None = None,
    xfades: list[float] | None = None,
    voiceover_captions: "list[tuple[object, Transcript]] | None" = None,
    emphasis: "Emphasis | None" = None,
) -> Path:
    """Produce `captions.ass` on disk. Always writes a valid ASS file.

    The subtitle track carries two things: spoken-word captions (mapped from
    each shot's source transcript onto the mezzanine timeline) and editor
    text overlays (already in mezzanine seconds). Either may be empty.

    Shot geometry comes from `clips` when given (the ACTUAL rendered shot
    list — possibly mixing assets and photos) or is reconstructed from the
    reel's scenes. `xfades` is the per-cut crossfade duration list; a single
    reel-wide value is derived from config when omitted.

    Prefers user-edited transcripts (`transcript_store.load_override_sync`)
    per asset. `emphasis` (compose/emphasis.py) picks the punch-mode key
    words; without it the keywords.py heuristic does.
    """
    out_path = reel_dir / "captions.ass"
    width, height = config.resolution
    mode = config.captions.mode

    effective = effective_analyses(analysis, analyses)

    # ----- shot geometry: (asset_id, src_start, src_end, duration) -----
    shots: list[tuple[str | None, float | None, float | None, float]] = []
    if clips is not None:
        shots = clip_shots(clips, analysis.asset_id)
    else:
        from reelforge_core.compose.clips import clip_bounds

        n = len(reel.scene_indices)
        for position, idx in enumerate(reel.scene_indices):
            scene = analysis.scenes[idx]
            s_, e_ = clip_bounds(
                position,
                n,
                scene,
                config,
                analysis,
                reel_start=reel.start_sec,
                reel_end=reel.end_sec,
            )
            if end_trims is not None and position < n - 1 and position < len(end_trims):
                e_ = max(s_ + 0.5, e_ - end_trims[position])
            shots.append((analysis.asset_id, s_, e_, e_ - s_))

    if xfades is None:
        single = config.transition.duration_sec if config.transition.kind != "cut" else 0.04
        xfades = [single] * max(0, len(shots) - 1)
    segments = map_segments(shots, xfades)
    cum = sum(d for *_, d in shots)

    # QA sidecar: every spoken word on the mezzanine timeline, WHATEVER the
    # caption mode — the scorecard needs hook latency, dead air and the
    # closing line even when captions are off. It never touches the render.
    try:
        _write_spoken_words(reel_dir / "words.json", segments, effective, voiceover_captions)
    except Exception as exc:  # noqa: BLE001
        log.warning("words.json not written: %s", exc)

    buf = [_header(width, height, config.captions)]
    caption_events: list[str] = []

    # ----- voiceover captions -----
    # Takes are already on the mezzanine timeline: a word at `w.start` in the
    # take sits at `take.start_sec + w.start`. While a take plays it owns the
    # caption band (footage audio is ducked beneath it), so footage words
    # inside any take's span are suppressed below.
    vo_spans: list[tuple[float, float]] = []
    total_len = cum
    if mode != "off":
        for take, transcript in (voiceover_captions or []):
            if transcript is None or getattr(take, "effective_gain", 1.0) <= 0:
                continue
            t0 = max(0.0, float(getattr(take, "start_sec", 0.0)))
            words = [
                w for seg in transcript.segments for w in seg.words
                if w.word.strip() and t0 + (w.start + w.end) / 2.0 <= total_len + 1e-6
            ]
            if not words:
                continue
            vo_spans.append((t0, t0 + max(w.end for w in words)))
            caption_events.extend(
                _render_word_events(words, lambda t, _t0=t0: max(0.0, _t0 + t), config)
            )

    def _covered(t: float) -> bool:
        return any(a - 1e-6 <= t <= b + 1e-6 for a, b in vo_spans)

    # ----- spoken-word captions, per segment -----
    if mode != "off":
        for aid, src_start, src_end, mezz_start in segments:
            rep = effective.get(aid)
            if rep is None or rep.transcript is None:
                continue
            seg_words = segment_words(rep, src_start, src_end)

            def _mt(t: float, _ms: float = mezz_start, _ss: float = src_start) -> float:
                return max(0.0, _ms + (t - _ss))

            # Footage words under a voiceover take yield to the take's captions.
            seg_words = [w for w in seg_words if not _covered(_mt((w.start + w.end) / 2.0))]
            if not seg_words:
                continue
            lit = None
            if emphasis is not None:
                lit = [emphasis.is_emphasised(aid, w.start) for w in seg_words]
            caption_events.extend(_render_word_events(seg_words, _mt, config, lit))

    # ----- text overlays (editor) -----
    overlay_events = [
        _overlay_event(o, width, height, config.captions)
        for o in (overlays or [])
        if o.text.strip() and o.end_sec > o.start_sec
    ]

    if not caption_events and not overlay_events:
        write_text_atomic(out_path, EMPTY_ASS.format(w=width, h=height))
        return out_path

    buf.extend(caption_events)
    buf.extend(overlay_events)
    write_text_atomic(out_path, "".join(buf))
    return out_path


def _write_spoken_words(
    out_path: Path,
    segments: list[tuple[str, float, float, float]],
    effective: "dict[str, AnalysisReport | None]",
    voiceover_captions: "list[tuple[object, Transcript]] | None",
) -> None:
    """Footage and voiceover words in mezzanine time, sorted. Footage words
    under a voiceover take are dropped, as captions drop them: the take is
    what the viewer hears there."""
    spoken: list[dict] = []
    vo_spans: list[tuple[float, float]] = []
    for take, transcript in voiceover_captions or []:
        if transcript is None or getattr(take, "effective_gain", 1.0) <= 0:
            continue
        t0 = max(0.0, float(getattr(take, "start_sec", 0.0)))
        take_words = [w for seg in transcript.segments for w in seg.words if w.word.strip()]
        if not take_words:
            continue
        vo_spans.append((t0, t0 + max(w.end for w in take_words)))
        spoken.extend(
            {"start": round(t0 + w.start, 3), "end": round(t0 + w.end, 3),
             "word": w.word.strip(), "source": "voiceover"}
            for w in take_words
        )
    for shot_index, (aid, src_start, src_end, mezz_start) in enumerate(segments):
        rep = effective.get(aid)
        if rep is None or rep.transcript is None:
            continue
        for seg in rep.transcript.segments:
            if seg.end < src_start or seg.start > src_end:
                continue
            for w in seg.words:
                if not w.word.strip():
                    continue
                mid = (w.start + w.end) / 2.0
                if not src_start <= mid <= src_end + 1e-6:
                    continue
                start = mezz_start + (w.start - src_start)
                if any(a <= start <= b for a, b in vo_spans):
                    continue
                # `shot` lets QA tell a stall inside one shot (the speaker
                # paused and nobody cut it) from a gap across a cut (an edit).
                spoken.append(
                    {"start": round(max(0.0, start), 3),
                     "end": round(max(0.0, mezz_start + (w.end - src_start)), 3),
                     "word": w.word.strip(), "source": "footage", "shot": shot_index}
                )
    spoken.sort(key=lambda w: w["start"])
    write_text_atomic(out_path, json.dumps({"words": spoken}, indent=1))


def has_dialogue(ass_path: Path) -> bool:
    """True when the ASS file carries at least one event worth burning in."""
    try:
        return "Dialogue:" in ass_path.read_text(encoding="utf-8")
    except OSError:
        return False
