def _fmt_time(sec: float) -> str:
    """ASS time: H:MM:SS.cc (centiseconds)."""
    sec = max(0.0, sec)
    h = int(sec // 3600)
    sec -= h * 3600
    m = int(sec // 60)
    sec -= m * 60
    cs = int(round(sec * 100))
    s = cs // 100
    cs_only = cs % 100
    return f"{h}:{m:02d}:{s:02d}.{cs_only:02d}"


_EMOJI = re.compile(
    "["
    "\U0001F000-\U0001FAFF"  # pictographs, emoticons, transport, symbols
    "\U00002600-\U000027BF"  # misc symbols, dingbats
    "\U0001F1E6-\U0001F1FF"  # flags
    "\u200d\ufe0f\u20e3"      # joiners and variation selectors
    "]+"
)


def strip_emoji(text: str) -> str:
    """Burned-in text can't show colour emoji — libass draws an empty box
    (the director's "🛹" hook did exactly that). Drop them, tidy spaces."""
    return re.sub(r"\s{2,}", " ", _EMOJI.sub("", text)).strip()


def _escape_text(text: str) -> str:
    """Escape literal `{` / `}` so ASS doesn't interpret them as tag delimiters."""
    return text.replace("\\", "\\\\").replace("{", r"\{").replace("}", r"\}")


def _alignment_for(position: str) -> int:
    return {"lower_third": 2, "centered": 5, "top": 8}[position]


def _bold_flag(font_family: str) -> int:
    """A family that names its weight ("Montserrat Black") already IS that
    weight; asking libass for bold on top makes it synthesize a smear."""
    heavy = ("Black", "ExtraBold", "Extra Bold", "Heavy", "Bold")
    return 0 if any(h in font_family for h in heavy) else 1


def _measure_bold(font_family: str) -> bool:
    """Captions always render heavy: a weight-named family is that weight
    and anything else gets ASS bold. Measure the bold face either way —
    measuring Inter at regular weight packed lines ~3% too wide and pushed
    full static lines past the safe edge."""
    del font_family  # one rule for every family; kept for call-site clarity
    return True


def _safe_margins(width: int, height: int, position: str) -> tuple[int, int, int]:
    """(MarginL, MarginR, MarginV) that keep text inside the platform-safe
    rectangle: the bottom edge for lower_third, the top edge for top."""
    r = safe_rect(width, height)
    margin_l, margin_r = int(round(r.x0)), int(round(width - r.x1))
    if position == "lower_third":
        margin_v = int(round(height - r.y1))
    elif position == "top":
        margin_v = int(round(r.y0))
    else:
        margin_v = 0
    return margin_l, margin_r, margin_v


def _safe_width(width: int, height: int, *, outline: float = 0.0, shadow: float = 0.0) -> float:
    """Width available to the GLYPHS: the safe rectangle minus the outline
    and shadow drawn around them. Packing to the bare safe width let a full
    line's outline spill ~18px past the safe edge."""
    return safe_rect(width, height).width - 2 * (outline + shadow) - 4


def _header(width: int, height: int, style: CaptionStyle) -> str:
    alignment = _alignment_for(style.position)
    margin_l, margin_r, margin_v = _safe_margins(width, height, style.position)
    bold = _bold_flag(style.font_family)
    return (
        "[Script Info]\n"
        "; Generated by ReelForge\n"
        "ScriptType: v4.00+\n"
        f"PlayResX: {width}\n"
        f"PlayResY: {height}\n"
        "ScaledBorderAndShadow: yes\n"
        "WrapStyle: 2\n"
        "\n"
        "[V4+ Styles]\n"
        "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, "
        "OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, "
        "ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, "
        "Alignment, MarginL, MarginR, MarginV, Encoding\n"
        f"Style: Default,{style.font_family},{style.font_size_px},"
        f"{style.primary_color},{style.highlight_color},{style.outline_color},"
        f"&H80000000,{bold},0,0,0,100,100,0,0,1,"
        f"{style.outline_width_px},{style.shadow_px},{alignment},"
        f"{margin_l},{margin_r},{margin_v},1\n"
        # Text overlays (editor, director hook). Size/colour/alignment are
        # set inline per event; the style supplies the font, a heavier
        # outline and the same safe side margins.
        f"Style: Overlay,{style.font_family},84,&H00FFFFFF,&H00FFFFFF,"
        f"&H00000000,&H80000000,{bold},0,0,0,100,100,0,0,1,5,2,5,"
        f"{margin_l},{margin_r},0,1\n"
        "\n"
        "[Events]\n"
        "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, "
        "Effect, Text\n"
    )


def _event(start: float, end: float, text: str, *, layer: int = 0) -> str:
    return (
        f"Dialogue: {layer},{_fmt_time(start)},{_fmt_time(end)},Default,,0,0,0,,"
        f"{_escape_text(text)}\n"
    )


def _event_raw(start: float, end: float, text: str, *, layer: int = 0) -> str:
    """Like _event, but `text` may contain ASS override tags — the caller is
    responsible for escaping the literal tokens."""
    return (
        f"Dialogue: {layer},{_fmt_time(start)},{_fmt_time(end)},Default,,0,0,0,,"
        f"{text}\n"
    )


def _inline_color(ass_color: str) -> str:
    """Convert a style color (&HAABBGGRR) into an inline \\c override (&HBBGGRR&)."""
    hexpart = ass_color.strip().removeprefix("&H").removesuffix("&")
    return f"\\c&H{hexpart[-6:]}&"


